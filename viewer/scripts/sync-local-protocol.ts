// Rust owns the protocol. Keep browser request/task/receipt types generated from
// its checked-in JSON Schema, so a new native field cannot silently drift.
import path from "node:path";
const root = path.resolve(import.meta.dirname, "../..");
const schema = await Bun.file(path.join(root, "schemas/local.json")).json();
const quote = (s: string) => JSON.stringify(s);
function type(s: any): string {
  if (s === true || !s || !Object.keys(s).length) return "unknown";
  if (s === false) return "never";
  if (s.$ref) return "Wire" + s.$ref.split("/").at(-1);
  if (Object.hasOwn(s, "const")) return quote(s.const);
  if (s.enum) return s.enum.map((x: any) => JSON.stringify(x)).join(" | ");
  if (s.oneOf || s.anyOf)
    return (s.oneOf ?? s.anyOf).map((v: any) => `(${type(v)})`).join(" | ");
  if (Array.isArray(s.type))
    return s.type.map((v: string) => type({ ...s, type: v })).join(" | ");
  if (s.type === "null") return "null";
  if (s.type === "string") return "string";
  if (s.type === "number" || s.type === "integer") return "number";
  if (s.type === "boolean") return "boolean";
  if (s.type === "array")
    return s.prefixItems
      ? `[${s.prefixItems.map(type).join(", ")}]`
      : `Array<${type(s.items)}>`;
  if (s.type === "object" || s.properties) {
    const fields = Object.entries(s.properties ?? {}).map(
      ([key, value]) =>
        `${quote(key)}${s.required?.includes(key) ? "" : "?"}: ${type(value)}`,
    );
    if (s.additionalProperties && s.additionalProperties !== false)
      fields.push(`[key: string]: ${type(s.additionalProperties)}`);
    return `{ ${fields.join("; ")} }`;
  }
  return "unknown";
}
const roots = [
  "request",
  "project",
  "receipt",
  "socket_client",
  "socket_server",
  "face_annotation",
];
const pascal = (s: string) =>
  s
    .split("_")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
const rootNames = new Set(roots.map(pascal));
const definitions: Record<string, any> = {};
for (const key of roots)
  for (const [name, value] of Object.entries(schema[key].$defs ?? {})) {
    if (rootNames.has(name)) continue;
    if (
      definitions[name] &&
      JSON.stringify(definitions[name]) !== JSON.stringify(value)
    )
      throw Error("Conflicting schema definition: " + name);
    definitions[name] = value;
  }
let output =
  "// Generated by bun run scripts/sync-local-protocol.ts from schemas/local.json.\n// Do not edit by hand.\n";
for (const [name, value] of Object.entries(definitions))
  output += `export type Wire${name} = ${type(value)};\n`;
for (const name of roots)
  output += `export type Wire${pascal(name)} = ${type(schema[name])};\n`;
const file = path.join(root, "viewer/src/local/generated.ts");
if (process.argv.includes("--check")) {
  if ((await Bun.file(file).text()) !== output)
    throw Error(
      "Local protocol types are stale; run bun run scripts/sync-local-protocol.ts",
    );
} else await Bun.write(file, output);
